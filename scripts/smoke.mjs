// Teste de fumaça: abre o app, escolhe idioma, passa por todas as abas e tira capturas.
import { chromium } from 'playwright';
const url = 'file://' + process.cwd() + '/dist/index.html';
const out = '/tmp/claude-0/shots/';
const lang = process.argv[2] || 'pt';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const errors = [];
const configs = [['m', { width: 390, height: 844 }, 'light'], ['d', { width: 1440, height: 900 }, 'dark']];
for (const [name, vp, scheme] of configs) {
  const page = await browser.newPage({ viewport: vp, colorScheme: scheme, isMobile: name === 'm', hasTouch: name === 'm' });
  page.on('pageerror', (e) => errors.push(`${name}: ${e}`));
  page.on('console', (m) => { if (m.type() === 'error' || m.text().includes('i18n')) errors.push(`${name} console: ${m.text()}`); });
  await page.goto(url);
  await page.waitForTimeout(700);
  await page.screenshot({ path: out + name + '-0splash.png' });
  await page.waitForTimeout(2000);
  await page.screenshot({ path: out + name + '-1lang.png' });
  const langIdx = { pt: 0, en: 1, es: 2, fr: 3, de: 4, zh: 5, ja: 6 }[lang];
  await page.locator('.lang-opt').nth(langIdx).click();
  await page.click('.lang-card .btn.primary');
  await page.waitForTimeout(500);
  await page.screenshot({ path: out + name + '-2home.png', fullPage: true });
  const nav = name === 'm' ? '.bottom-tabs' : '.top-tabs';
  await page.click(`${nav} [data-tab=sim]`);
  await page.waitForTimeout(800);
  await page.click('.run-btn');
  await page.waitForTimeout(2500);
  await page.screenshot({ path: out + name + '-3sim.png' });
  await page.locator('.panel-tabs button').nth(2).click();
  await page.waitForTimeout(200);
  await page.screenshot({ path: out + name + '-4robot.png' });
  await page.locator('.panel-tabs button').nth(3).click();
  await page.click('.match-panel .btn.primary.wide');
  await page.waitForTimeout(400);
  await page.locator('.stage .speed').selectOption('4');
  await page.waitForTimeout(4000);
  await page.screenshot({ path: out + name + '-5match.png' });
  await page.locator('.panel-tabs button').nth(0).click();
  await page.locator('.code-head .seg button').nth(1).click();
  await page.waitForTimeout(300);
  await page.screenshot({ path: out + name + '-6blocks.png' });
  await page.click('.stage-tools .icon-btn >> nth=0');
  await page.waitForTimeout(400);
  const box = await page.locator('.stage-host').boundingBox();
  await page.mouse.click(box.x + box.width * 0.6, box.y + box.height * 0.45);
  await page.mouse.click(box.x + box.width * 0.6, box.y + box.height * 0.7);
  await page.waitForTimeout(300);
  await page.screenshot({ path: out + name + '-7ruler.png' });
  await page.click('.stage-tools .icon-btn >> nth=2');
  await page.waitForTimeout(600);
  await page.screenshot({ path: out + name + '-8fs.png' });
  await page.click('.stage-tools .icon-btn >> nth=2');
  await page.click(`${nav} [data-tab=learn]`);
  await page.waitForTimeout(400);
  await page.screenshot({ path: out + name + '-9learn.png' });
  await page.click(`${nav} [data-tab=path]`);
  await page.waitForTimeout(300);
  await page.screenshot({ path: out + name + '-10path.png' });
  await page.locator('.node.open button').first().click();
  await page.waitForTimeout(300);
  await page.click('.player-foot .btn.primary');
  await page.locator('.option').nth(1).click();
  await page.click('.player-foot .btn.primary');
  await page.waitForTimeout(300);
  await page.screenshot({ path: out + name + '-11player.png' });
  await page.click('.player-top .icon-btn');
  await page.click(`${nav} [data-tab=score]`);
  await page.waitForTimeout(300);
  await page.locator('.check-item').nth(0).click();
  await page.locator('.count-item .stepper button:last-child').first().click();
  await page.screenshot({ path: out + name + '-12score.png' });
  await page.click('.top-right .icon-btn');
  await page.waitForTimeout(400);
  await page.screenshot({ path: out + name + '-13settings.png' });
  await page.close();
}
console.log('errors', errors.length ? errors : 'none');
await browser.close();
